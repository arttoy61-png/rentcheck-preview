const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {records,sandbox}=require('./audit-redevelopment-records.cjs'),card=sandbox.window.RentRedevelopmentCard;
const before=JSON.stringify(records),banghwa=records.find(p=>(p.registry?.id||p.id)==='cleanup-banghwa6'),closed=records.find(p=>card.isClosed(p));
assert.ok(card.searchText(banghwa).includes('래미안 엘라비네'));
assert.ok(card.searchText(banghwa).includes('608-97'));
assert.equal(records.filter(p=>card.aliases(p).length).length,1);
assert.ok(!card.questions(closed).includes('<h3>지금 매수하면?'));
assert.ok(!card.questions(closed).includes('<h4>조합원 지위 승계'));
assert.ok(card.questions(closed).includes('해산·청산 기록 확인'));
assert.ok(card.questions(banghwa).includes('문의할 질문'));
const app=fs.readFileSync(require('node:path').join(__dirname,'../app/app.js'),'utf8');
const scope={window:sandbox.window,state:{sub:'sites',listLimit:80},filteredProjects:()=>records};
vm.createContext(scope);
for(const name of ['redevelopmentRows','redevelopmentMapProjects','visibleRedevelopmentProjects'])vm.runInContext(app.split('\n').find(l=>l.startsWith('function '+name+'(')),scope);
assert.equal(scope.visibleRedevelopmentProjects().length,80);
const a=scope.redevelopmentMapProjects().map(p=>p.id).join();
scope.state.listLimit=160;
assert.equal(scope.visibleRedevelopmentProjects().length,160);
assert.equal(scope.redevelopmentMapProjects().map(p=>p.id).join(),a);
assert.equal(scope.redevelopmentMapProjects().length,records.length);
assert.equal(JSON.stringify(records),before);
assert.ok(card.mapItems([closed])[0].official_name.startsWith('[종료]'));
console.log('PASS independent map candidates, list pagination, immutable records, scoped verified alias, closed-state guidance');
